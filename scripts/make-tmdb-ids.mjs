// Builds src/data/tmdbIds.js: catalog title id -> TMDB { type, id }, read from the
// trailer research file (which records each title's TMDB page).
// Run from the project root: node scripts/make-tmdb-ids.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const research = JSON.parse(readFileSync('supabase/seed/trailers-research.json', 'utf8'));
const lines = [];
for (const t of research.titles) {
  // Most entries have source "movie/278"; titles without a trailer only have the TMDB page URL.
  const ref = t.source ?? new URL(t.tmdb).pathname.slice(1);
  const m = /^(movie|tv)\/(\d+)$/.exec(ref);
  if (!m) throw new Error(`No TMDB id for ${t.id}`);
  lines.push(`  '${t.id}': { type: '${m[1]}', id: ${m[2]} },`);
}

writeFileSync(
  'src/data/tmdbIds.js',
  `// Generated by scripts/make-tmdb-ids.mjs from supabase/seed/trailers-research.json. Do not edit by hand.
// Maps each DramaStream title id to its TMDB movie or series, so catalog titles can show full cast.
export const TMDB_IDS = {
${lines.join('\n')}
};

/** The TMDB { type, id } for a catalog title id, or null when we don't have one. */
export const tmdbRefFor = (titleId) => TMDB_IDS[titleId] ?? null;
`,
);
console.log(`Wrote ${lines.length} ids to src/data/tmdbIds.js`);
