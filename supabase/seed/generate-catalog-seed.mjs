// Turns src/data/catalog.js into supabase/seed/catalog.sql.
// Run from the project root:  node supabase/seed/generate-catalog-seed.mjs
// Options: --only id1,id2  (just those titles)  --out path  (default catalog.sql)
// The SQL is idempotent (safe to run twice) and looks ids up by name, so it
// never depends on generated ids.
import { writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const { LOCAL_CATALOG: fullCatalog, FEATURED_TITLE_ID } = await import(
  pathToFileURL(join(here, '../../src/data/catalog.js'))
);
const arg = (name) => {
  const i = process.argv.indexOf(name);
  return i > -1 ? process.argv[i + 1] : null;
};
const only = arg('--only')?.split(',');
const outFile = arg('--out') ?? join(here, 'catalog.sql');
// Row order within a type comes from the full catalog, even when seeding a few titles.
const sortOrder = new Map();
const seenOfType = {};
for (const t of fullCatalog) {
  seenOfType[t.type] = (seenOfType[t.type] ?? -1) + 1;
  sortOrder.set(t.id, seenOfType[t.type]);
}
const catalog = only ? fullCatalog.filter((t) => only.includes(t.id)) : fullCatalog;

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const n = (v) => (v === null || v === undefined ? 'null' : Number(v));

const lines = [
  '-- Generated by supabase/seed/generate-catalog-seed.mjs from src/data/catalog.js. Do not edit by hand.',
  'begin;',
  '',
];

const titleRows = catalog.map((t) => {
  return `  (${[
    q(t.id), q(t.title), q(t.type), q(t.synopsis), n(t.releaseYear), q(t.contentRating),
    n(t.runtimeMinutes), n(t.seasons), n(t.episodeCount), t.limitedSeries ? 'true' : 'false',
    q(t.castLabel), q(t.heroPosition), t.id === FEATURED_TITLE_ID ? 'true' : 'false', sortOrder.get(t.id),
  ].join(', ')})`;
});
lines.push(
  'insert into public.titles (id, title, type, synopsis, release_year, content_rating, runtime_minutes, seasons, episode_count, limited_series, cast_label, hero_position, is_featured, sort_order) values',
  titleRows.join(',\n'),
  'on conflict (id) do update set title = excluded.title, type = excluded.type, synopsis = excluded.synopsis, release_year = excluded.release_year, content_rating = excluded.content_rating, runtime_minutes = excluded.runtime_minutes, seasons = excluded.seasons, episode_count = excluded.episode_count, limited_series = excluded.limited_series, cast_label = excluded.cast_label, hero_position = excluded.hero_position, is_featured = excluded.is_featured, sort_order = excluded.sort_order;',
  '',
);

const genres = [...new Set(catalog.flatMap((t) => t.genres))];
lines.push(`insert into public.genres (name) values ${genres.map((g) => `(${q(g)})`).join(', ')} on conflict (name) do nothing;`, '');

const people = [...new Set(catalog.flatMap((t) => [...t.credits.flatMap((c) => c.names), ...t.cast]))];
lines.push(`insert into public.people (name) values\n${people.map((p) => `  (${q(p)})`).join(',\n')}\non conflict (name) do nothing;`, '');

const genreRows = catalog.flatMap((t) => t.genres.map((g, i) => `(${q(t.id)}, ${q(g)}, ${i})`));
lines.push(
  'insert into public.title_genres (title_id, genre_id, position)',
  'select v.title_id, g.id, v.position from (values',
  `  ${genreRows.join(',\n  ')}`,
  ') as v(title_id, genre, position) join public.genres g on g.name = v.genre',
  'on conflict (title_id, genre_id) do update set position = excluded.position;',
  '',
);

const creditRows = catalog.flatMap((t) =>
  [...t.credits, { role: 'Cast', names: t.cast }].flatMap((c, r) =>
    c.names.map((name, i) => `(${q(t.id)}, ${q(name)}, ${q(c.role)}, ${r}, ${i})`),
  ),
);
lines.push(
  'insert into public.credits (title_id, person_id, role, role_position, position)',
  'select v.title_id, p.id, v.role, v.role_position, v.position from (values',
  `  ${creditRows.join(',\n  ')}`,
  ') as v(title_id, name, role, role_position, position) join public.people p on p.name = v.name',
  'on conflict (title_id, role, person_id) do update set role_position = excluded.role_position, position = excluded.position;',
  '',
);

const series = catalog.filter((t) => t.type === 'series');
lines.push(
  'insert into public.seasons (title_id, season_number)',
  'select v.title_id, s from (values',
  `  ${series.map((t) => `(${q(t.id)}, ${n(t.seasons)})`).join(',\n  ')}`,
  ') as v(title_id, seasons), generate_series(1, v.seasons) as s',
  'on conflict do nothing;',
  '',
  'insert into public.episodes (title_id, season_number, episode_number, name, runtime_minutes) values',
  series
    .filter((t) => t.firstEpisode)
    .map((t) => {
      const ep = t.firstEpisode;
      return `  (${q(t.id)}, ${n(ep.season)}, ${n(ep.episode)}, ${q(ep.title)}, ${n(ep.runtimeMinutes)})`;
    })
    .join(',\n'),
  'on conflict (title_id, season_number, episode_number) do update set name = excluded.name, runtime_minutes = excluded.runtime_minutes;',
);

lines.push('', 'commit;', '');
writeFileSync(outFile, lines.join('\n'));
console.log(`Wrote catalog.sql: ${catalog.length} titles, ${genres.length} genres, ${people.length} people.`);
