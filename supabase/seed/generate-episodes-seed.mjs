// Turns supabase/seed/episodes.json (every episode of every series: titles,
// runtimes and stills from TMDB season pages, synopses written for this
// project) into supabase/seed/episodes.sql. Idempotent; run from the root:
//   node supabase/seed/generate-episodes-seed.mjs
// Options: --chunk N  also writes episodes-<i>.sql files of at most N rows each.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const { series } = JSON.parse(readFileSync(join(here, 'episodes.json'), 'utf8'));
const chunkArg = process.argv.indexOf('--chunk');
const chunkSize = chunkArg > -1 ? Number(process.argv[chunkArg + 1]) : 0;

// Compact rows: t = title id, s/e = season/episode, n = name, r = runtime, y = synopsis, p = still path.
const rows = Object.entries(series).flatMap(([t, eps]) =>
  eps.map((x) => ({ t, s: x.season, e: x.episode, n: x.title, r: x.runtimeMinutes, y: x.synopsis, p: x.still })),
);

const sql = (list) => `insert into public.episodes (title_id, season_number, episode_number, name, runtime_minutes, synopsis, still_path)
select t, s, e, n, r, y, p from jsonb_to_recordset($json$${JSON.stringify(list)}$json$::jsonb)
  as x(t text, s smallint, e smallint, n text, r smallint, y text, p text)
on conflict (title_id, season_number, episode_number) do update
  set name = excluded.name, runtime_minutes = excluded.runtime_minutes,
      synopsis = excluded.synopsis, still_path = excluded.still_path;
`;

const header = '-- Generated by supabase/seed/generate-episodes-seed.mjs from episodes.json. Do not edit by hand.\n';
writeFileSync(join(here, 'episodes.sql'), header + sql(rows));
console.log(`Wrote episodes.sql: ${rows.length} episodes.`);

if (chunkSize > 0) {
  for (let i = 0; i * chunkSize < rows.length; i += 1) {
    writeFileSync(join(here, `episodes-${i + 1}.sql`), sql(rows.slice(i * chunkSize, (i + 1) * chunkSize)));
  }
}
