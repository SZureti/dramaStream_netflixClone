// Turns supabase/seed/episodes.json (every episode of every series, from TMDB
// season pages) into supabase/seed/episodes.sql. Idempotent; run from the root:
//   node supabase/seed/generate-episodes-seed.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const { series } = JSON.parse(readFileSync(join(here, 'episodes.json'), 'utf8'));
const q = (v) => `'${String(v).replace(/'/g, "''")}'`;

const rows = Object.entries(series).flatMap(([titleId, eps]) =>
  eps.map((e) => `(${q(titleId)}, ${e.season}, ${e.episode}, ${q(e.title)}, ${e.runtimeMinutes})`),
);

const sql = `-- Generated by supabase/seed/generate-episodes-seed.mjs from episodes.json. Do not edit by hand.
insert into public.episodes (title_id, season_number, episode_number, name, runtime_minutes) values
  ${rows.join(',\n  ')}
on conflict (title_id, season_number, episode_number) do update
  set name = excluded.name, runtime_minutes = excluded.runtime_minutes;
`;
writeFileSync(join(here, 'episodes.sql'), sql);
console.log(`Wrote episodes.sql: ${rows.length} episodes.`);
